// Regenerates assets/site/icons.svg from the Font Awesome Free 6.7.2 SVGs named in src/icons.ts.
// Run: npm --workspace @gcpe/public-site run icons:build (the output is committed).
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ICONS } from "../src/icons";

const here = dirname(fileURLToPath(import.meta.url));
const fa = dirname(createRequire(import.meta.url).resolve("@fortawesome/fontawesome-free/package.json"));

const symbols = Object.entries(ICONS).map(([id, src]) => {
  const svg = readFileSync(join(fa, "svgs", `${src}.svg`), "utf8");
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  const paths = [...svg.matchAll(/<path\b[^>]*?\bd="([^"]+)"/g)].map((m) => m[1]!);
  if (!viewBox || paths.length === 0) throw new Error(`${src}: no viewBox or path`);
  return `<symbol id="i-${id}" viewBox="${viewBox}">${paths.map((d) => `<path d="${d}"/>`).join("")}</symbol>`;
});

const out = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Font Awesome Free 6.7.2 by @fontawesome - https://fontawesome.com
     License - https://fontawesome.com/license/free (Icons: CC BY 4.0)
     Generated by apps/public-site/scripts/build-icons.ts; do not edit by hand. -->
<svg xmlns="http://www.w3.org/2000/svg" fill="currentColor">
${symbols.join("\n")}
</svg>
`;
writeFileSync(join(here, "../assets/site/icons.svg"), out);
console.log(`wrote ${symbols.length} symbols`);
