export function backupScript(stamp: string): string {
  stampOk(stamp);
  const dumpFiles = BOXS_APPS.map((a) => `"$DIR/${a.app}.sql.gz"`).join(" ");
  return [
    PRELUDE,
    `DIR="$HOME/gcpe-data/backups/${stamp}"`,
    'mkdir -p "$DIR"',
    `for pair in ${BOXS_APPS.map((a) => `${a.app}:${a.envVar}`).join(" ")}; do`,
    '  app="${pair%%:*}"; var="${pair#*:}"',
    '  u="$(url_of "$var")"',
    '  pg_url_noauth "$u"',
    '  pg_dump --format=plain --no-owner --no-acl --dbname="$PGURL_NOAUTH" | gzip > "$DIR/$app.sql.gz"',
    '  unset PGPASSWORD',
    '  echo "dumped $app"',
    "done",
    'tar -C "$HOME/gcpe-data" -czf "$DIR/site-output.tar.gz" site-output',
    // Verified before COMPLETE is written: a restore from this backup only has to trust the
    // marker, never re-check seven dumps and a tarball itself.
    `for f in ${dumpFiles}; do validate_dump "$f"; done`,
    'validate_tar "$DIR/site-output.tar.gz"',
    ': > "$DIR/COMPLETE"',
    'echo "backup size (KB): $(du -sk "$DIR" | cut -f1)"',
    "",
  ].join("\n");
}

export function restoreScript(o: { stamp: string; from: "scrub-load" | "backups"; apps: string[]; resetNodPositions: boolean; siteOutput: "clear" | "restore" }): string {
  stampOk(o.stamp);
  if (o.from !== "scrub-load" && o.from !== "backups") throw new ScrubArgumentError('--from must be "scrub-load" or "backups"');
  if (o.siteOutput !== "clear" && o.siteOutput !== "restore") throw new ScrubArgumentError('--site-output must be "clear" or "restore"');
  const apps = o.apps.map(appOf);
  const sed = DUMP_FILTER_SED.map((x) => `'${x}'`).join(" ");
  return [
    PRELUDE,
    `SRC="$HOME/gcpe-data/${o.from}/${o.stamp}"`,
    ...(o.from === "backups" ? ['[ -f "$SRC/COMPLETE" ] || { echo "backup is missing its COMPLETE marker" >&2; exit 1; }'] : []),
    // Every input is checked here, before the first drop: a missing or damaged file now aborts
    // with nothing touched, instead of leaving an earlier app already replaced by the time a
    // later one turns out to be missing.
    ...apps.map((a) => `validate_dump "$SRC/${a.app}.sql.gz"`),
    ...(o.siteOutput === "restore" ? ['validate_tar "$SRC/site-output.tar.gz"'] : []),
    'DROP_SQL="$(mktemp)"',
    'TMP_SO=""',
    "trap 'rm -f \"$DROP_SQL\"; [ -n \"$TMP_SO\" ] && rm -rf \"$TMP_SO\"' EXIT",
    "cat > \"$DROP_SQL\" <<'DROPSQL'",
    DROP_MINE_SQL.trimEnd(),
    "DROPSQL",
    "restore_one() {",
    '  local app="$1" var="$2" u',
    '  u="$(url_of "$var")"',
    '  pg_url_noauth "$u"',
    `  { cat "$DROP_SQL"; gunzip -c "$SRC/$app.sql.gz" | sed ${sed}; } | PGOPTIONS='-c client_min_messages=warning' psql "$PGURL_NOAUTH" -X -q -v ON_ERROR_STOP=1 --single-transaction -f - >/dev/null`,
    '  unset PGPASSWORD',
    '  echo "restored $app"',
    "}",
    ...apps.map((a) => `restore_one ${a.app} ${a.envVar}`),
    ...(o.resetNodPositions
      ? [
          'u="$(url_of NOD_DATABASE_URL)"',
          'pg_url_noauth "$u"',
          `PGOPTIONS='-c client_min_messages=warning' psql "$PGURL_NOAUTH" -X -q -v ON_ERROR_STOP=1 -c "DELETE FROM inbox_positions WHERE source IN ('core', 'nrms')" >/dev/null`,
          'unset PGPASSWORD',
          'echo "cleared NoD positions for core and nrms"',
        ]
      : []),
    ...(o.siteOutput === "clear"
      ? ['mkdir -p "$HOME/gcpe-data/site-output"', 'find "$HOME/gcpe-data/site-output" -mindepth 1 -delete', 'echo "cleared site-output: the site rebuilds on start"']
      : [
          // Extracted to a scratch directory and swapped in with one `mv`, so a tar that fails
          // partway through never leaves site-output half-deleted and half-restored. The scratch
          // directory is under the same parent as the real one (not the system tmp, which can be
          // a different filesystem) so that `mv` is a same-filesystem rename, not a copy.
          'mkdir -p "$HOME/gcpe-data"',
          'TMP_SO="$(mktemp -d "$HOME/gcpe-data/site-output-swap.XXXXXX")"',
          'tar -C "$TMP_SO" -xzf "$SRC/site-output.tar.gz"',
          'rm -rf "$HOME/gcpe-data/site-output"',
          'mv "$TMP_SO/site-output" "$HOME/gcpe-data/site-output"',
          'echo "restored site-output"',
        ]),
    "",
  ].join("\n");
}

export function tickScript(site: string, times: number): string {
  if (!/^https:\/\/[A-Za-z0-9.-]+$/.test(site)) throw new ScrubArgumentError("--site must be an https origin");
  if (!Number.isFinite(times) || times < 1) throw new ScrubArgumentError("--times must be a positive whole number");
  const n = Math.trunc(times);
  return [
    PRELUDE,
    'TOKEN_FILE="$HOME/.gcpe-tick-token"',
    '[ -r "$TOKEN_FILE" ] || { echo "cannot read the tick token" >&2; exit 1; }',
    `for i in $(seq 1 ${n}); do`,
    // The token goes to curl through its stdin config, not as a header argument: an argument
    // would sit in this process's command line, visible to anyone who can run `ps` as this user.
    `  printf 'header = "Authorization: Bearer %s"\\n' "$(cat "$TOKEN_FILE")" | curl -fsS -X POST --config - "${site}/stack/tick" >/dev/null`,
    "  sleep 5",
    "done",
    'echo "ticked"',
    "",
  ].join("\n");
}

export async function runRemote(host: string, script: string, o: { capture?: boolean } = {}): Promise<string> {
  return new Promise((res, rej) => {
    const child = spawn("ssh", ["-o", "BatchMode=yes", host, "bash", "-s"], { stdio: ["pipe", o.capture ? "pipe" : "inherit", "inherit"] });
    let out = "";
    child.stdout?.on("data", (d: Buffer) => { out += d.toString("utf8"); });
    // Writing the whole script in one `end()` can outlive a remote that's already exited (a
    // `set -e` failure closes its stdin fast); without this, that EPIPE would be an unhandled
    // error event and crash the process instead of surfacing through `close` below.
    child.stdin?.on("error", () => {});
    child.on("error", rej);
    // `close` (not `exit`) fires only once stdio is fully drained, so a captured script's last
    // bytes of output can't be lost to a race between the exit event and the final `data` event.
    child.on("close", (code) => (code === 0 ? res(out) : rej(new ScrubStepError(`a step on ${host} failed (exit ${code})`))));
    child.stdin!.end(script);
  });
}

function sha256File(path: string): Promise<string> {
  return new Promise((res, rej) => {
    const h = createHash("sha256");
    const s = createReadStream(path);
    s.on("error", rej);
    s.on("data", (d: string | Buffer) => h.update(d));
    s.on("end", () => res(h.digest("hex")));
  });
}

export async function uploadFile(host: string, localPath: string, stamp: string, name: string): Promise<void> {
  stampOk(stamp);
  if (!/^[a-z-]+\.sql\.gz$/.test(name)) throw new ScrubArgumentError("upload names are <app>.sql.gz");
  const size = statSync(localPath).size;
  const sha256 = await sha256File(localPath);
  const dir = `$HOME/gcpe-data/scrub-load/${stamp}`;
  // Written to a `.part` name, then only moved into place once its size and checksum match the
  // local file: a connection cut mid-upload leaves a `.part` file a later restore won't see,
  // never a short write masquerading as the complete one.
  const remote = [
    "umask 077",
    `mkdir -p "${dir}"`,
    `cat > "${dir}/${name}.part"`,
    `sz=$(wc -c < "${dir}/${name}.part" | tr -d ' ')`,
    `sum=$(sha256sum "${dir}/${name}.part" | cut -d ' ' -f1)`,
    `if [ "$sz" = "${size}" ] && [ "$sum" = "${sha256}" ]; then mv "${dir}/${name}.part" "${dir}/${name}"; else echo "upload of ${name} didn't verify" >&2; rm -f "${dir}/${name}.part"; exit 1; fi`,
  ].join(" && ");
  const child = spawn("ssh", ["-o", "BatchMode=yes", host, remote], { stdio: ["pipe", "inherit", "inherit"] });
  let doneErr: unknown;
  const done = new Promise<void>((res, rej) => {
    child.on("error", (e) => { doneErr = e; rej(e); });
    child.on("close", (code) => {
      if (code === 0) res();
      else { const e = new ScrubStepError(`uploading ${name} failed (exit ${code})`); doneErr = e; rej(e); }
    });
  });
  // Attached before the write below: if `ssh` has already exited by the time the pipeline fails,
  // this is the rejection that was going to happen anyway, not a second, unhandled one.
  done.catch(() => {});
  child.stdin!.on("error", () => {});
  try {
    await pipeline(createReadStream(localPath), child.stdin!);
  } catch (e) {
    await done.catch(() => {});
    throw doneErr ?? e;
  }
  await done;
}

export async function downloadBackup(host: string, stamp: string, localFile: string): Promise<void> {
  stampOk(stamp);
  mkdirSync(dirname(localFile), { recursive: true, mode: 0o700 });
  const partFile = `${localFile}.part`;
  const child = spawn("ssh", ["-o", "BatchMode=yes", host, `tar -C "$HOME/gcpe-data/backups" -cf - ${stamp}`], { stdio: ["ignore", "pipe", "inherit"] });
  const done = new Promise<void>((res, rej) => { child.on("error", rej); child.on("close", (code) => (code === 0 ? res() : rej(new ScrubStepError(`downloading the backup failed (exit ${code})`)))); });
  // Written to a `.part` name first, renamed into place only once the remote `tar` has actually
  // succeeded: a dropped connection or a remote failure leaves a `.part` behind, never an empty
  // or truncated file sitting at the name a later restore would read.
  done.catch(() => {});
  try {
    await pipeline(child.stdout!, createWriteStream(partFile, { mode: 0o600 }));
    await done;
  } catch (e) {
    rmSync(partFile, { force: true });
    throw e;
  }
  renameSync(partFile, localFile);
}

/** A plain-SQL dump, gzipped, after checking it holds nothing boxs.ca's user can't restore. */
export async function localDump(url: string, outFile: string): Promise<void> {
  mkdirSync(dirname(outFile), { recursive: true, mode: 0o700 });
  const u = new URL(url);
  // `URL.password` is still percent-encoded (the URL was built with it, same as every DB URL
  // here) — decoded here because PGPASSWORD is taken literally, unlike the URL libpq itself
  // decodes when parsing a whole connection string.
  const password = decodeURIComponent(u.password);
  u.password = "";
  const child = spawn("pg_dump", ["--format=plain", "--no-owner", "--no-acl", `--dbname=${u.toString()}`], { stdio: ["ignore", "pipe", "inherit"], env: { ...process.env, PGPASSWORD: password } });
  const done = new Promise<void>((res, rej) => { child.on("error", rej); child.on("close", (code) => (code === 0 ? res() : rej(new ScrubStepError(`pg_dump failed (exit ${code})`)))); });
  const gzip = createGzip();
  const out = createWriteStream(outFile, { mode: 0o600 });
  const written = pipeline(gzip, out);
  // Attached before the loop below: a refusal inside it destroys `gzip`, and without these
  // handlers already in place that would be an unhandled rejection (and, previously, a crash)
  // rather than something the catch block below can act on.
  done.catch(() => {});
  written.catch(() => {});
  try {
    let inCopy = false;
    // `pg_dump`'s plain-format output is always bare-\n between lines (it's generated on this
    // machine, never on Windows), and readline already normalises \r\n itself, so there's no
    // stray \r left on `line` to strip here — a line is only ever cut on \n.
    for await (const line of createInterface({ input: child.stdout!, crlfDelay: Infinity })) {
      if (inCopy) {
        if (line === "\\.") inCopy = false;
      } else if (/^COPY .* FROM stdin;$/.test(line)) {
        inCopy = true;
      } else {
        const why = unsafeDumpLine(line);
        if (why) throw new ScrubStepError(`the dump holds ${why}`);
      }
      if (!gzip.write(`${line}\n`)) await new Promise((r) => gzip.once("drain", r));
    }
    gzip.end();
    await Promise.all([done, written]);
  } catch (e) {
    child.kill();
    gzip.destroy();
    out.destroy();
    rmSync(outFile, { force: true });
    throw e;
  }
}
